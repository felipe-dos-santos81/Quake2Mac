/* ---- stub refimport --------------------------------------------------- */

static void stub_Con_Printf (int print_level, char *fmt, ...)
{
	(void)print_level; (void)fmt;
}

static int stub_FS_LoadFile (char *name, void **buf)
{
	char	path[2048];
	FILE	*f;
	long	len;

	snprintf (path, sizeof(path), "%s/%s", tmpdir, name);
	f = fopen (path, "rb");
	if (!f)
	{
		if (buf)
			*buf = NULL;
		return -1;
	}
	fseek (f, 0, SEEK_END);
	len = ftell (f);
	fseek (f, 0, SEEK_SET);
	if (buf)
	{
		*buf = malloc (len + 1);
		fread (*buf, 1, len, f);
		((char *)*buf)[len] = 0;
	}
	fclose (f);
	return (int)len;
}

static void stub_FS_FreeFile (void *buf)
{
	free (buf);
}

static void write_file (const char *name, const unsigned char *data, size_t len)
{
	char	path[2048];
	FILE	*f;

	snprintf (path, sizeof(path), "%s/%s", tmpdir, name);
	f = fopen (path, "wb");
	if (!f) { perror (path); exit (2); }
	fwrite (data, 1, len, f);
	fclose (f);
}

static void remove_file (const char *name)
{
	char	path[2048];

	snprintf (path, sizeof(path), "%s/%s", tmpdir, name);
	unlink (path);
}

/* ---- tests ------------------------------------------------------------- */

static void test_override_path (void)
{
	char	out[MAX_QPATH];
	char	small[16];

	CHECK (GL_OverridePath ("textures/e1u1/PIP04_4.wal", "png", out, sizeof(out)));
	CHECK (!strcmp (out, "textures/e1u1/pip04_4.png"));

	CHECK (GL_OverridePath ("textures/e1u1/floor1_1.WAL", "jpg", out, sizeof(out)));
	CHECK (!strcmp (out, "textures/e1u1/floor1_1.jpg"));

	CHECK (!GL_OverridePath ("textures/e1u1/floor1_1.pcx", "png", out, sizeof(out)));
	CHECK (!GL_OverridePath (".wal", "png", out, sizeof(out)));
	CHECK (!GL_OverridePath ("textures/e1u1/floor1_1.wal", "png", small, sizeof(small)));
	CHECK (GL_OverridePath ("a.wal", "png", small, sizeof(small)));
	CHECK (!strcmp (small, "a.png"));
}

static void test_load_png_rgba (void)
{
	int		w = 0, h = 0;
	byte	*pix;

	write_file (PNG, png2x2, sizeof(png2x2));
	pix = GL_LoadOverride (WAL, &w, &h);
	CHECK (pix != NULL);
	CHECK (w == 2 && h == 2);
	if (pix)
	{
		CHECK (pix[0] == 255 && pix[1] == 0   && pix[2] == 0   && pix[3] == 255);	/* (0,0) red */
		CHECK (pix[4] == 0   && pix[5] == 255 && pix[6] == 0   && pix[7] == 255);	/* (1,0) green */
		CHECK (pix[8] == 0   && pix[9] == 0   && pix[10] == 255 && pix[11] == 255);	/* (0,1) blue */
		CHECK (pix[15] == 0);															/* (1,1) alpha 0 */
		GL_FreeOverride (pix);
	}
	remove_file (PNG);
}

static void test_probe_order_png_tga_jpg (void)
{
	int		w, h;
	byte	*pix;

	write_file (PNG, png2x2, sizeof(png2x2));
	write_file (TGA, tga2x2_green, sizeof(tga2x2_green));
	write_file (JPG, jpg2x2_blue, sizeof(jpg2x2_blue));

	pix = GL_LoadOverride (WAL, &w, &h);						/* png wins */
	CHECK (pix && pix[0] == 255 && pix[1] == 0 && pix[2] == 0);
	GL_FreeOverride (pix);

	remove_file (PNG);
	pix = GL_LoadOverride (WAL, &w, &h);						/* then tga */
	CHECK (pix && pix[0] == 0 && pix[1] == 255 && pix[2] == 0 && pix[3] == 255);
	GL_FreeOverride (pix);

	remove_file (TGA);
	pix = GL_LoadOverride (WAL, &w, &h);						/* then jpg */
	CHECK (pix && w == 2 && h == 2 && pix[0] < 16 && pix[1] < 16 && pix[2] > 240);
	GL_FreeOverride (pix);

	remove_file (JPG);
	pix = GL_LoadOverride (WAL, &w, &h);						/* nothing left */
	CHECK (pix == NULL);
}

static void test_corrupt_file_falls_through (void)
{
	int		w, h;
	byte	*pix;

	write_file (PNG, corrupt_png, sizeof(corrupt_png));
	write_file (TGA, tga2x2_green, sizeof(tga2x2_green));
	pix = GL_LoadOverride (WAL, &w, &h);						/* bad png skipped, tga used */
	CHECK (pix && pix[1] == 255 && pix[0] == 0);
	GL_FreeOverride (pix);

	remove_file (TGA);
	pix = GL_LoadOverride (WAL, &w, &h);						/* only the bad png -> NULL */
	CHECK (pix == NULL);
	remove_file (PNG);
}

static void test_non_wal_name_is_not_probed (void)
{
	int		w, h;

	write_file (PNG, png2x2, sizeof(png2x2));
	CHECK (GL_LoadOverride ("textures/e1u1/floor1_1.pcx", &w, &h) == NULL);
	remove_file (PNG);
}

int main (void)
{
	char		sub[1100];
	const char	*base = getenv ("TMPDIR");

	snprintf (tmpdir, sizeof(tmpdir), "%s/q2_override_XXXXXX", base ? base : "/tmp");
	if (!mkdtemp (tmpdir)) { perror ("mkdtemp"); return 2; }
	snprintf (sub, sizeof(sub), "%s/textures", tmpdir);
	mkdir (sub, 0700);
	snprintf (sub, sizeof(sub), "%s/textures/e1u1", tmpdir);
	mkdir (sub, 0700);

	ri.Con_Printf = stub_Con_Printf;
	ri.FS_LoadFile = stub_FS_LoadFile;
	ri.FS_FreeFile = stub_FS_FreeFile;

	test_override_path ();
	test_load_png_rgba ();
	test_probe_order_png_tga_jpg ();
	test_corrupt_file_falls_through ();
	test_non_wal_name_is_not_probed ();

	rmdir (sub);
	snprintf (sub, sizeof(sub), "%s/textures", tmpdir);
	rmdir (sub);
	rmdir (tmpdir);

	if (failures)
	{
		fprintf (stderr, "test_override: %d failure(s)\n", failures);
		return 1;
	}
	printf ("test_override: all checks passed\n");
	return 0;
}
